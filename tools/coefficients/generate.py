"""Emit per-precision coefficient headers for the CPU backend.

Every artifact is self-validating. The log_gamma INTERVAL polynomial is
fit in the centered variable t = x - 2 over [-1, 1] (a monomial fit in x
on [1, 3] is too ill-conditioned to survive the cast to machine
precision); downstream code evaluates polevl(x - 2.0, ...). chebfit_auto()
validates what actually ships: coefficients are cast to the target
precision and evaluated with Horner in that precision on a dense grid
against 60-dps truth, and the fit is rejected unless the worst relative
error meets its target. The asymptotic series constructors assert the
next-term truncation bound at the chosen threshold. Headers land in
special_functions_cpu/generated/ and are checked in; regeneration must
be byte-identical (tests/test_generated_clean.py).
"""

from pathlib import Path

import mpmath as mp
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / "special_functions_cpu" / "generated"


def chebfit_auto(f, a, b, target_rel, dtype=np.float64, max_terms=40):
    """Fit f on [a, b] and validate the fit exactly as it ships.

    The mp-precision Chebyshev fit is cast to `dtype` and evaluated with
    Horner in `dtype` arithmetic on a dense grid; the fit is accepted only
    if the worst relative error against 60-dps truth is within target_rel.
    """
    with mp.workdps(60):
        for n_terms in range(6, max_terms + 1):
            coeffs = mp.chebyfit(f, [a, b], n_terms)
            cast = [dtype(float(c)) for c in coeffs]
            worst = 0.0
            for x in np.linspace(a, b, 2001):
                xt = dtype(x)
                acc = dtype(0.0)
                for c in cast:
                    acc = acc * xt + c
                true = f(mp.mpf(float(xt)))
                worst = max(worst, abs(float((mp.mpf(float(acc)) - true) / true)))
            if worst <= target_rel:
                return [float(c) for c in cast]
    raise RuntimeError(f"no fit reached {target_rel} within {max_terms} terms")


def stirling_coefficients(threshold, target_rel, max_terms=16):
    # log_gamma tail: sum_{n>=1} B_2n / (2n(2n-1)) * x^(1-2n).
    with mp.workdps(60):
        terms = [mp.bernoulli(2 * n) / (2 * n * (2 * n - 1)) for n in range(1, max_terms + 1)]
        value_scale = abs(mp.log(mp.gamma(threshold)))
        for n_used in range(3, max_terms):
            next_term = abs(terms[n_used]) * mp.mpf(threshold) ** (1 - 2 * (n_used + 1))
            if next_term < target_rel * value_scale:
                return [float(t) for t in reversed(terms[:n_used])]
    raise RuntimeError("stirling series does not converge to target at threshold")


def digamma_tail_coefficients(threshold, target_rel, max_terms=16):
    # psi tail: ln x - 1/(2x) - sum_{n>=1} B_2n/(2n) * x^(-2n).
    with mp.workdps(60):
        terms = [mp.bernoulli(2 * n) / (2 * n) for n in range(1, max_terms + 1)]
        value_scale = abs(mp.digamma(threshold))
        for n_used in range(3, max_terms):
            next_term = abs(terms[n_used]) * mp.mpf(threshold) ** (-2 * (n_used + 1))
            if next_term < target_rel * value_scale:
                return [float(t) for t in reversed(terms[:n_used])]
    raise RuntimeError("digamma series does not converge to target at threshold")


def _emit(path: Path, macro_prefix: str, arrays: dict, scalars: dict, c_type: str, comments: dict | None = None):
    suffix = "f" if c_type == "float" else ""
    fmt = "%.9e" if c_type == "float" else "%.17e"
    lines = [
        "// GENERATED by tools/coefficients/generate.py -- DO NOT EDIT.",
        "#pragma once",
        "",
    ]
    for name, values in arrays.items():
        if comments and name in comments:
            lines.append(f"// {comments[name]}")
        lines.append(f"static const {c_type} {macro_prefix}_{name}[] = {{")
        for v in values:
            lines.append(f"    {fmt % v}{suffix},")
        lines.append("};")
        lines.append(f"#define {macro_prefix}_{name}_N {len(values)}")
        lines.append("")
    for name, v in scalars.items():
        lines.append(f"#define {macro_prefix}_{name} {fmt % v}{suffix}")
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path.relative_to(ROOT)}")


def _lg(x):
    # log_gamma(x) / ((x-1)(x-2)): removable 0/0 at x=1 and x=2 (log_gamma
    # vanishes at both). mpmath's chebyfit evaluates f exactly at the
    # interval midpoint (t=0, i.e. x=2) for every N, and mpf division
    # raises on literal 0/0, so continue smoothly via L'Hopital:
    # limit = digamma(x) / (2x - 3), i.e. euler at x=1, 1 - euler at x=2.
    if x == 1:
        return -mp.digamma(1)
    if x == 2:
        return mp.digamma(2)
    return mp.log(abs(mp.gamma(x))) / ((x - 1) * (x - 2))


def _lg_centered(t):
    # Centered interval function: t = x - 2, t in [-1, 1].
    return _lg(t + 2)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for c_type, dt, np_dtype, series_target, interval_target, lg_thresh, dg_thresh in (
        ("double", "FLOAT64", np.float64, 2.0**-56, 4e-16, 13.0, 10.0),
        ("float", "FLOAT32", np.float32, 2.0**-27, 2.4e-7, 8.0, 6.0),
    ):
        _emit(
            OUT_DIR / f"log_gamma_{dt.lower()}.h",
            f"SF_LOG_GAMMA_{dt}",
            {
                "INTERVAL": chebfit_auto(_lg_centered, -1.0, 1.0, interval_target, dtype=np_dtype),
                "STIRLING": stirling_coefficients(lg_thresh, series_target),
            },
            {"STIRLING_THRESHOLD": lg_thresh},
            c_type,
            comments={"INTERVAL": "polynomial in t = x - 2, t in [-1, 1]"},
        )
        _emit(
            OUT_DIR / f"digamma_{dt.lower()}.h",
            f"SF_DIGAMMA_{dt}",
            {"TAIL": digamma_tail_coefficients(dg_thresh, series_target)},
            {"TAIL_THRESHOLD": dg_thresh},
            c_type,
        )


if __name__ == "__main__":
    main()
